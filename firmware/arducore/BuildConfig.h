#ifndef ARDUCORE_PROFILE
#define ARDUCORE_PROFILE 0
#endif
#if ARDUCORE_PROFILE < 0 || ARDUCORE_PROFILE > 5
#error ARDUCORE_PROFILE must be in 0..5
#endif
#define ARDUCORE_DISTANCE (ARDUCORE_PROFILE == 0 || ARDUCORE_PROFILE == 2)
#define ARDUCORE_TEMPERATURE (ARDUCORE_PROFILE == 0 || ARDUCORE_PROFILE == 3)
#define ARDUCORE_BUZZER (ARDUCORE_PROFILE == 0 || ARDUCORE_PROFILE == 4)
#define ARDUCORE_SERVO (ARDUCORE_PROFILE == 0 || ARDUCORE_PROFILE == 5)
#endif
